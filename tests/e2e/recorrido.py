"""Prueba de punta a punta en un navegador real (Chromium) con un Supabase FALSO.
Uso:  python3 tests/e2e/recorrido.py        (desde la carpeta del proyecto)
Guarda capturas en tests/e2e/capturas/. Comprueba además que no hay errores de consola ni de CSP.
"""
import http.server, threading, functools, os, sys, re, datetime
from playwright.sync_api import sync_playwright, expect

RAIZ = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
CAP = os.path.join(os.path.dirname(__file__), 'capturas')
os.makedirs(CAP, exist_ok=True)
FALSO = open(os.path.join(os.path.dirname(__file__), 'falso_supabase.js'), encoding='utf-8').read()
CSV = os.path.join(RAIZ, '..', 'importar', 'menu-26oct-8nov-2026.csv')
if not os.path.exists(CSV):
    CSV = os.path.join(RAIZ, 'importar', 'menu-26oct-8nov-2026.csv')

class Silencioso(http.server.SimpleHTTPRequestHandler):
    def log_message(self, *a): pass
srv = http.server.ThreadingHTTPServer(('127.0.0.1', 8123), functools.partial(Silencioso, directory=RAIZ))
threading.Thread(target=srv.serve_forever, daemon=True).start()
URL = 'http://127.0.0.1:8123/'

fallos, errores = [], []
def comprobar(cond, msg):
    print(('  OK  ' if cond else '  FALLO ') + msg)
    if not cond: fallos.append(msg)

def entrar_como(page, quien):
    page.evaluate(f"localStorage.setItem('falso_entrar_como','{quien}')")

def tab(page, nombre):
    page.locator('nav.tabs button', has_text=nombre).click()
    page.wait_for_timeout(150)

with sync_playwright() as p:
    b = p.chromium.launch()
    ctx = b.new_context(viewport={'width': 390, 'height': 844}, timezone_id='Europe/Madrid', locale='es-ES',
                        service_workers='block', accept_downloads=True)
    ctx.route('**/js/supabase.min.js', lambda r: r.fulfill(body=FALSO, content_type='application/javascript'))
    page = ctx.new_page()
    page.clock.set_fixed_time(datetime.datetime(2026, 10, 23, 10, 0, 0))
    page.on('console', lambda m: errores.append(f'consola[{m.type}]: {m.text}') if m.type in ('error', 'warning') and 'Service Worker registration blocked' not in m.text else None)
    page.on('pageerror', lambda e: errores.append(f'pageerror: {e}'))
    page.on('dialog', lambda d: d.accept())

    print('1) Jorge: login y calendario nuevo')
    page.goto(URL)
    expect(page.get_by_role('button', name='Entrar con Google')).to_be_visible()
    page.screenshot(path=f'{CAP}/01-login.png')
    entrar_como(page, 'jorge')
    page.get_by_role('button', name='Entrar con Google').click()
    expect(page.get_by_role('button', name='Crear calendario')).to_be_visible()
    page.get_by_role('button', name='Crear calendario').click()
    expect(page.locator('nav.tabs')).to_be_visible()
    comprobar(True, 'calendario creado y marco visible')
    comprobar(page.locator('.aviso-invitar').count() == 1, 'tarjeta "Invitar a tu pareja" aparece estando solo')

    print('2) Jorge invita a Paula')
    tab(page, 'Más')
    page.get_by_label('Correo a invitar').fill('Paula@Test.com ')
    page.get_by_role('button', name=re.compile('Invitar|Enviar')).first.click()
    page.wait_for_timeout(300)
    comprobar('paula@test.com' in page.locator('#contenido').inner_text().lower(), 'invitación pendiente listada en minúsculas')
    page.screenshot(path=f'{CAP}/02-mas-invitada.png', full_page=True)

    print('3) Jorge crea eventos de cada tipo')
    def nuevo_evento(tipo, titulo, fecha, ini='', fin='', rep=None, hasta=None, notas=''):
        tab(page, 'Inicio')
        page.locator('.fab').click()
        page.locator('.tipo-btn', has_text=tipo).click()
        page.get_by_label('Título').fill(titulo)
        page.get_by_label('Fecha').fill(fecha)
        if ini: page.get_by_label('Hora de inicio').fill(ini)
        if fin: page.get_by_label('Hora de fin').fill(fin)
        if notas: page.get_by_label('Notas').fill(notas)
        if rep:
            page.get_by_label('Repetición').select_option(rep)
            if hasta: page.get_by_label('Repetir hasta').fill(hasta)
        page.locator('.modal').get_by_role('button', name='Guardar').click()
        page.wait_for_timeout(300)
    nuevo_evento('Deporte', 'Pilates', '2026-10-26', '19:00', '20:00', rep='semanal', hasta='2026-11-30')
    nuevo_evento('Plan', 'Cine', '2026-10-24', '21:30', '23:30')
    nuevo_evento('Tarea', 'Sacar pollo del congelador', '2026-10-23', '08:00')
    nuevo_evento('Compromiso', 'Dentista', '2026-10-27', '12:00', '12:30')
    comprobar(page.locator('.modal').count() == 0, 'el editor se cierra al guardar')

    print('4) Vista Inicio (Hoy / Mañana)')
    tab(page, 'Inicio')
    txt = page.locator('#contenido').inner_text()
    comprobar('Sacar pollo' in txt, 'la tarea de hoy aparece en Hoy')
    page.locator('.seg button', has_text='Mañana').click()
    page.wait_for_timeout(200)
    txt = page.locator('#contenido').inner_text()
    comprobar('Para dejar preparado hoy' in txt or 'preparar' in txt.lower(), 'sección de preparar en Mañana')
    comprobar('Cine' in txt, 'el plan de mañana (24/10) aparece')
    page.screenshot(path=f'{CAP}/03-inicio-manana.png', full_page=True)

    print('5) Calendario: rejilla mensual y filtro por tipo')
    tab(page, 'Calendario')
    comprobar(page.locator('.dia').count() in (35, 42), f'rejilla con {page.locator(".dia").count()} días')
    comprobar(page.locator('.dia .chip', has_text='Pilates').count() >= 1, 'Pilates repetido semanal en la rejilla (octubre)')
    n_pilates = page.locator('.dia:not(.fuera) .chip', has_text='Pilates').count()
    comprobar(n_pilates == 1, f'Pilates en octubre: solo el lunes 26 (la serie empieza ahí) → {n_pilates}')
    page.locator('.chip-tipo', has_text='Deporte').click()
    page.wait_for_timeout(200)
    comprobar(page.locator('.dia .chip', has_text='Pilates').count() == 0, 'desactivar "Deporte" oculta Pilates')
    page.locator('.chip-tipo', has_text='Deporte').click()
    page.get_by_label('Mes siguiente').click()
    page.wait_for_timeout(300)
    comprobar(page.locator('.dia:not(.fuera) .chip', has_text='Pilates').count() == 5, 'noviembre: Pilates los lunes 2, 9, 16, 23 y 30 → '
              + str(page.locator('.dia:not(.fuera) .chip', has_text='Pilates').count()))
    page.get_by_label('Mes anterior').click()
    page.wait_for_timeout(200)
    page.screenshot(path=f'{CAP}/04-calendario.png', full_page=True)

    print('6) Borrar solo un día de la serie')
    page.locator('.dia:not(.fuera)', has=page.locator('.num', has_text=re.compile(r'^26$'))).first.click()
    page.locator('.fila-evento', has_text='Pilates').click()
    page.get_by_role('button', name='Borrar').click()
    page.wait_for_timeout(200)
    page.screenshot(path=f'{CAP}/05-borrar-serie.png')
    page.get_by_role('button', name=re.compile('^Solo el 26')).click()
    page.wait_for_timeout(300)
    comprobar(page.locator('.dia:not(.fuera) .chip', has_text='Pilates').count() == 0, 'borrado solo el 26/10; no queda Pilates en octubre')
    page.get_by_label('Mes siguiente').click(); page.wait_for_timeout(300)
    comprobar(page.locator('.dia:not(.fuera) .chip', has_text='Pilates').count() == 5, 'el resto de la serie (noviembre) sigue')

    print('7) Cambio a Paula y acepta la invitación')
    tab(page, 'Más')
    page.get_by_role('button', name='Cerrar sesión').click()
    expect(page.get_by_role('button', name='Entrar con Google')).to_be_visible()
    entrar_como(page, 'paula')
    page.get_by_role('button', name='Entrar con Google').click()
    expect(page.get_by_role('button', name='Aceptar')).to_be_visible()
    page.screenshot(path=f'{CAP}/06-paula-invitacion.png')
    page.get_by_role('button', name='Aceptar').click()
    expect(page.locator('nav.tabs')).to_be_visible()
    comprobar(page.locator('.chip-capa').count() == 2, 'Paula ve las dos capas (suya y de Jorge)')
    tab(page, 'Más')
    lista = page.locator('.personas').first.inner_text()
    comprobar('Paula' in lista and 'Jorge' in lista and 'pareja' in lista, 'lista de personas con ambos')
    colores = page.locator('.personas li').evaluate_all("els => els.map(e => getComputedStyle(e).getPropertyValue('--c').trim())")
    comprobar(len(set(colores)) == 2, f'colores distintos: {colores}')

    print('8) Paula ve el evento de Jorge y puede editarlo (pareja)')
    tab(page, 'Calendario')
    page.locator('.barra-nav button.pequeno').click(); page.wait_for_timeout(300)
    page.locator('.dia:not(.fuera)', has=page.locator('.num', has_text=re.compile(r'^27$'))).first.click()
    comprobar('Dentista' in page.locator('.agenda').inner_text(), 'Paula ve "Dentista" de Jorge')
    page.locator('.fila-evento', has_text='Dentista').click()
    comprobar(page.get_by_role('button', name='Guardar').count() == 1, 'como pareja puede editar el evento de Jorge')
    page.get_by_label('Cerrar').click()

    print('9) Paula crea un evento para los dos')
    tab(page, 'Inicio')
    page.locator('.fab').click()
    page.locator('.tipo-btn', has_text='Plan').click()
    page.get_by_label('Título').fill('Cena con amigos')
    page.get_by_label('Fecha').fill('2026-10-30')
    page.get_by_label('Hora de inicio').fill('21:00')
    checks = page.locator('.quien-lista input[type=checkbox]')
    comprobar(checks.count() == 2, 'selector "Para" con las dos personas')
    for i in range(checks.count()):
        if not checks.nth(i).is_checked(): checks.nth(i).check()
    page.locator('.modal').get_by_role('button', name='Guardar').click()
    page.wait_for_timeout(300)
    tab(page, 'Calendario')
    page.locator('.dia:not(.fuera)', has=page.locator('.num', has_text=re.compile(r'^30$'))).first.click()
    comprobar(page.locator('.agenda .fila-evento', has_text='Cena con amigos').count() == 2, 'el evento "para los dos" crea una fila por persona')
    page.screenshot(path=f'{CAP}/07-paula-calendario.png', full_page=True)

    print('10) Plantilla de Excel y importación del menú real en .xlsx (como Jorge)')
    import csv, tempfile, openpyxl
    tmp = tempfile.mkdtemp()
    tab(page, 'Más')
    with page.expect_download() as d:
        page.get_by_role('button', name=re.compile('Descargar plantilla')).first.click()
    plantilla = os.path.join(tmp, 'plantilla.xlsx'); d.value.save_as(plantilla)
    wbp = openpyxl.load_workbook(plantilla)
    comprobar(d.value.suggested_filename == 'plantilla-menu-organizapp.xlsx' and wbp.sheetnames == ['Menú', 'Cómo rellenar'], f'plantilla descargada y válida: {wbp.sheetnames}')
    # CSV guardado por Excel sin UTF-8 (tildes en Windows-1252) y un archivo que no es Excel
    open(os.path.join(tmp, 'win.csv'), 'wb').write('Fecha;Persona;Franja;Hora;Texto\r\n02/11/2026;Jorge;Media mañana;11:00;Plátano y té\r\n'.encode('cp1252'))
    page.get_by_role('button', name=re.compile('Importar menú')).first.click()
    page.get_by_label('Archivo de Excel').set_input_files(os.path.join(tmp, 'win.csv'))
    expect(page.locator('.modal')).to_contain_text('Hay 1 comidas')
    comprobar(True, 'CSV en Windows-1252 se lee: 1 comida, franja «Media mañana» reconocida')
    open(os.path.join(tmp, 'malo.xlsx'), 'wb').write(b'esto no es un excel')
    page.get_by_label('Archivo de Excel').set_input_files(os.path.join(tmp, 'malo.xlsx'))
    page.wait_for_timeout(300)
    comprobar(page.locator('.modal .error-txt').count() == 1, 'archivo que no es Excel: error claro → ' + page.locator('.modal .error-txt').inner_text())
    page.get_by_label('Cerrar').click()
    # El menú real, convertido a un Excel como lo escribiría una persona: fechas y horas reales de Excel
    wb = openpyxl.Workbook(); ws = wb.active
    ws.append(['Fecha', 'Persona', 'Franja', 'Hora', 'Texto'])
    nombres = {'desayuno': 'Desayuno', 'media_manana': 'Media mañana', 'comida': 'Comida', 'merienda': 'Merienda', 'cena': 'Cena'}
    for r in csv.DictReader(open(CSV, encoding='utf-8')):
        hh = datetime.time(*map(int, r['hora'].split(':')[:2])) if r['hora'] else None
        ws.append([datetime.date.fromisoformat(r['fecha']), r['persona'], nombres[r['franja']], hh, r['texto']])
    xlsx = os.path.join(tmp, 'menu.xlsx'); wb.save(xlsx)
    page.get_by_role('button', name=re.compile('Importar menú')).first.click()
    page.get_by_label('Archivo de Excel').set_input_files(xlsx)
    expect(page.locator('.modal')).to_contain_text('132 comidas')
    comprobar(True, 'el Excel se lee: 132 comidas')
    sel = page.locator('.modal select')
    comprobar(sel.count() == 2, 'dos personas a emparejar (Jorge, Paula)')
    valores = [sel.nth(i).evaluate("s => s.options[s.selectedIndex].text") for i in range(sel.count())]
    comprobar(sorted(valores) == ['Jorge Pérez', 'Paula Gómez'], f'emparejadas por nombre: {valores}')
    page.screenshot(path=f'{CAP}/08-importar.png')
    page.locator('.modal').get_by_role('button', name='Importar').click()
    page.wait_for_timeout(600)
    comprobar(page.locator('.modal').count() == 0, 'importación cerrada')

    print('11) Menú de la semana del 26/10')
    comprobar('26' in page.locator('.barra-nav').inner_text(), 'la vista salta a la semana del 26/10: ' + page.locator('.barra-nav').inner_text().replace('\n', ' '))
    comprobar(page.locator('.dia-menu').count() == 7, f'{page.locator(".dia-menu").count()} tarjetas de día')
    page.screenshot(path=f'{CAP}/09-menu-semana.png', full_page=True)
    comprobar(page.locator('.celda:not(.vacia)').count() > 40, f'celdas con menú: {page.locator(".celda:not(.vacia)").count()}')

    print('12) Editar un día del menú')
    page.locator('.celda:not(.vacia)').first.click()
    expect(page.locator('.modal')).to_be_visible()
    page.screenshot(path=f'{CAP}/10-menu-editor.png')
    area = page.get_by_label('Cena', exact=True)
    area.fill('Crema de calabaza\nTortilla francesa')
    page.locator('.modal').get_by_role('button', name='Guardar').click()
    page.wait_for_timeout(400)
    comprobar('+1' in page.locator('.dia-menu').first.inner_text(), 'cena de 2 líneas muestra "+1"')

    print('13) Repetir semanas hasta el 30/11')
    page.get_by_role('button', name=re.compile('Repetir semanas')).click()
    expect(page.locator('.modal')).to_be_visible()
    page.get_by_label('Semana de origen').fill('2026-10-26')
    page.get_by_label('Semanas a copiar').select_option('2')
    page.get_by_label('Repetir hasta').fill('2026-11-30')
    page.screenshot(path=f'{CAP}/11-repetir.png')
    page.locator('.modal').get_by_role('button', name='Repetir').last.click()
    page.wait_for_timeout(800)
    page.get_by_label('Semana siguiente').click(); page.wait_for_timeout(300)
    page.get_by_label('Semana siguiente').click(); page.wait_for_timeout(300)  # semana del 9/11
    comprobar('9' in page.locator('.barra-nav').inner_text(), 'semana del 9/11: ' + page.locator('.barra-nav').inner_text().replace('\n', ' '))
    comprobar(page.locator('.celda:not(.vacia)').count() > 20, f'la semana del 9/11 ya tiene menú: {page.locator(".celda:not(.vacia)").count()} celdas')
    comprobar('Crema de calabaza' in page.locator('.dia-menu').first.inner_text(), 'el lunes 9/11 copia el lunes 26/10 (incluida la cena editada)')
    # la semana 9/11 debe equivaler a la semana 1 (26/10): el lunes 26/10 de Jorge tiene "Cena" editada → no cuenta; comparamos un día cualquiera de desayuno
    page.screenshot(path=f'{CAP}/12-menu-9nov.png', full_page=True)

    print('13b) Versión visible e instalación')
    ver = re.search(r"VERSION = '([^']+)'", open(os.path.join(RAIZ, 'sw.js'), encoding='utf-8').read()).group(1)
    tab(page, 'Inicio'); page.wait_for_timeout(300)
    comprobar(page.locator('.cab .version').inner_text() == 'v' + ver, 'recuadro de versión en la cabecera: ' + page.locator('.cab .version').inner_text())
    tab(page, 'Más')
    comprobar(page.locator('.version-txt').inner_text() == ver, 'versión también en Más')
    page.get_by_role('button', name=re.compile('Instalar en este móvil')).click()
    expect(page.locator('.modal')).to_contain_text('Instalar aplicación')
    comprobar(True, 'sin evento del navegador, el botón muestra la ayuda manual')
    page.get_by_role('button', name='Entendido').click()
    page.evaluate("window.__pr = 0; const e = new Event('beforeinstallprompt'); e.prompt = async () => { window.__pr++; }; e.userChoice = Promise.resolve({outcome:'accepted'}); window.dispatchEvent(e)")
    page.wait_for_timeout(300)
    page.get_by_role('button', name=re.compile('Instalar en este móvil')).click()
    page.wait_for_timeout(200)
    comprobar(page.evaluate('window.__pr') == 1 and page.locator('.modal').count() == 0, 'con el evento del navegador, el botón lanza la instalación directamente')

    print('14) Inicio con el menú de hoy y tema oscuro')
    tab(page, 'Inicio')
    page.screenshot(path=f'{CAP}/13-inicio-hoy.png', full_page=True)
    tab(page, 'Más')
    page.get_by_label('Aspecto').select_option('oscuro')
    page.wait_for_timeout(200)
    comprobar(page.evaluate("document.documentElement.dataset.tema") == 'oscuro', 'tema oscuro aplicado')
    page.screenshot(path=f'{CAP}/14-mas-oscuro.png', full_page=True)
    tab(page, 'Calendario')
    page.screenshot(path=f'{CAP}/15-calendario-oscuro.png', full_page=True)

    print('15) Sin desbordamiento horizontal en móvil')
    for t in ('Inicio', 'Calendario', 'Menú', 'Más'):
        tab(page, t)
        ancho = page.evaluate("[document.documentElement.scrollWidth, window.innerWidth]")
        comprobar(ancho[0] <= ancho[1], f'{t}: sin scroll horizontal ({ancho})')

    print('16) Páginas legales')
    for pg in ('privacidad.html', 'terminos.html'):
        r = page.goto(URL + pg)
        comprobar(r.status == 200, f'{pg} responde 200')

    b.close()

print('\nErrores de consola / CSP:')
for e in errores: print('  ', e)
comprobar(len(errores) == 0, 'ningún error ni aviso en consola')
print('\nRESULTADO:', 'TODO OK' if not fallos else f'{len(fallos)} FALLOS')
for f in fallos: print(' -', f)
sys.exit(1 if fallos else 0)
