class Silencioso(http.server.SimpleHTTPRequestHandler):
    def log_message(self, *a): pass
srv = http.server.ThreadingHTTPServer(('127.0.0.1', 8123), functools.partial(Silencioso, directory=RAIZ))
threading.Thread(target=srv.serve_forever, daemon=True).start()
URL = 'http://127.0.0.1:8123/'

fallos, errores = [], []
def comprobar(cond, msg):
    print(('  OK  ' if cond else '  FALLO ') + msg)
    if not cond: fallos.append(msg)

def entrar_como(page, quien):
    page.evaluate(f"localStorage.setItem('falso_entrar_como','{quien}')")

def tab(page, nombre):
    page.locator('nav.tabs button', has_text=nombre).click()
    page.wait_for_timeout(150)

